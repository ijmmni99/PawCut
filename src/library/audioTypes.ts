export type LibraryKind = 'music' | 'sfx' | 'voice';

/** A reusable audio file: a music track, a sound effect, or a recorded voiceover. Stored in OPFS under audio/. */
export type LibraryItem = {
  id: string;
  kind: LibraryKind;
  title: string;
  fileName: string;
  /** OPFS path of the audio file. */
  path: string;
  durationSec: number;
  /** Peak levels 0..1 for the waveform thumbnail. */
  waveform: number[];
  /** Music only. */
  bpm: number | null;
  /** Beat times in seconds of source (music only). */
  beats: number[];
  tags: string[];
  mood: string | null;
  /** SFX category (Whoosh, Pop, …). */
  category: string | null;
  favorite: boolean;
  licenseNote: string;
  /** Generated by PawCut (built-in SFX). */
  builtin: boolean;
  createdAt: number;
  lastUsedAt: number | null;
};

export const MUSIC_TAGS = ['cute', 'hype', 'chill', 'funny'];
export const MOODS = ['Happy', 'Energetic', 'Calm', 'Playful', 'Emotional'];
